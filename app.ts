import { movimentacaoRoutes } from "./src/routes/movimentacao.routes";
import { configuracaoRoutes } from "./src/routes/configuracao.routes";
import { analyticsRoutes } from "./src/routes/analytics.routes";
import { analyticsInputRoutes } from "./src/routes/analytics-input.routes";
import { partnerAdminRoutes } from "./src/routes/partner-admin.routes";
import { publicApiRoutes } from "./src/routes/public-api.routes";

export function criarApp(opcoes: { logger?: boolean } = {}) {
  const app = Fastify({ logger: opcoes.logger ?? true });
  const rateLimitRedis = process.env.REDIS_URL ? new IORedis(process.env.REDIS_URL, {
    maxRetriesPerRequest: 1, enableOfflineQueue: false, connectTimeout: 3_000,
    retryStrategy: (attempt) => Math.min(attempt * 250, 1_000),
  }) : undefined;
  const jwtSecret = process.env.JWT_SECRET;
  if (!jwtSecret || Buffer.byteLength(jwtSecret) < 32) {
    throw new Error("JWT_SECRET precisa estar definido e ter pelo menos 32 bytes.");
  }

  app.register(jwt, { secret: jwtSecret, sign: { expiresIn: "30m" } });
  app.register(rateLimit, { global: false, ...(rateLimitRedis ? { redis: rateLimitRedis, skipOnError: true } : {}) });
  if (rateLimitRedis) app.addHook("onClose", async () => { await rateLimitRedis.quit().catch(() => undefined); });
  app.register(swagger, {
    openapi: {
      info: { title: "GreenCode API", description: "API interna e API pública versionada do GreenCode.", version: "1.0.0" },
      components: { securitySchemes: {
        ApiKeyAuth: { type: "apiKey", in: "header", name: "x-api-key" },
        BearerAuth: { type: "http", scheme: "bearer", bearerFormat: "JWT" },
      } },
      tags: [
        { name: "API pública v1", description: "Integrações autorizadas de parceiros" },
        { name: "Análises internas", description: "Análises e jobs autenticados por JWT" },
        { name: "Dados analíticos", description: "Registro de observações, falhas, materiais e custos" },
        { name: "Administração", description: "Cadastro de parceiros e ciclo de vida das API Keys" },
      ],
    },
  });
  app.register(swaggerUi, { routePrefix: "/docs", uiConfig: { docExpansion: "list", deepLinking: false } });
  app.decorateRequest("authenticatedUser", null);
  app.decorateRequest("apiPrincipal", null);
  app.register(authRoutes);
  app.register(organizacaoRoutes);
  app.register(contratoVersionRoutes);
  app.register(loteVersionRoutes);
  app.register(equipamentoVersionRoutes);
  app.register(usuarioRoutes);
  app.register(journalRoutes);
  app.register(movimentacaoRoutes);
  app.register(configuracaoRoutes);
  app.register(analyticsRoutes);
  app.register(analyticsInputRoutes);
  app.register(partnerAdminRoutes);
  app.register(publicApiRoutes);

  return app;
}


